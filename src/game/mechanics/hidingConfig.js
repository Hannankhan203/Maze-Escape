export function isValidHidingSpotType(type) {
  return Boolean(type && Object.prototype.hasOwnProperty.call(HIDING_SPOT_CONFIG, type))
}

export function getHidingSpotConfig(type) {
  return isValidHidingSpotType(type) ? HIDING_SPOT_CONFIG[type] : null
}

/**
 * Converts local `(lx, lz)` coordinates relative to a hiding spot center/yaw
 * into world-space `{ x, z }`.
 */
export function localToWorldSpotOffset(centerX, centerZ, yaw, lx = 0, lz = 0) {
  const cos = Math.cos(yaw || 0)
  const sin = Math.sin(yaw || 0)
  return {
    x: centerX + lx * cos + lz * sin,
    z: centerZ - lx * sin + lz * cos,
  }
}
